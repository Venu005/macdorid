import Foundation

/// What the Mac's clipboard holds, after the app read it (images already converted to PNG).
public enum ClipboardContent: Equatable, Sendable {
    case text(String)
    case image(Data)
}

public enum PasteboardKind: Equatable, Sendable {
    case text, image, ignored
}

/// Which pasteboard items go to the phone (spec §4.1).
public enum ClipboardRules {
    /// Password managers and apps mark private or temporary items with these (nspasteboard.org).
    public static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
    ]
    public static let fileURLType = "public.file-url"
    public static let imageTypes: Set<String> = ["public.png", "public.tiff"]
    public static let textTypes: Set<String> = ["public.utf8-plain-text", "public.url"]
    private static let zeroID = "00000000-0000-0000-0000-000000000000"

    public static func kind(of types: [String]) -> PasteboardKind {
        let set = Set(types)
        if !set.isDisjoint(with: privateTypes) || set.contains(fileURLType) { return .ignored }
        if !set.isDisjoint(with: imageTypes) { return .image }
        if !set.isDisjoint(with: textTypes) { return .text }
        return .ignored
    }

    /// A single http(s) URL with nothing around it is a link; anything else is text.
    public static func kind(ofText text: String) -> ClipboardItem.Kind {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.contains(where: \.isWhitespace), let url = URL(string: trimmed),
              let scheme = url.scheme?.lowercased(), scheme == "http" || scheme == "https", url.host() != nil else { return .text }
        return .link
    }

    /// Bytes of the `clipboard.set` frame for `text`, JSON escaping included (spec §8.1).
    public static func encodedSize(of text: String) -> Int {
        let message = Message.clipboardSet(ClipboardSet(itemId: zeroID, text: text))
        return (try? MessageCodec.encode(message, id: zeroID))?.utf8.count ?? Int.max
    }

    public static func fitsInAFrame(_ text: String) -> Bool { encodedSize(of: text) <= ClipboardLimits.maxFrameBytes }
}

/// Which pasteboard change counts the watcher should report (spec §8.2): not the one it last saw, and never one
/// the app produced itself. Recording our own writes here (on the main actor, at write time) closes the race in
/// which the watcher reported the app's own write before `ClipboardSync` had recorded it.
public struct PasteboardChangeTracker: Sendable {
    private var last: Int

    public init(current: Int) { last = current }

    /// The app just wrote to the pasteboard, producing `changeCount`.
    public mutating func wrote(_ changeCount: Int) { last = changeCount }

    /// True when `changeCount` is a change someone else made since the last check.
    public mutating func isNewChange(_ changeCount: Int) -> Bool {
        guard changeCount != last else { return false }
        last = changeCount
        return true
    }
}
