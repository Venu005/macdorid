@Suite struct ClipboardRulesTests {
    // Review Focus #1
    @Test func concealedTransientAndAutoGeneratedAreIgnored() {
        for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
            #expect(ClipboardRules.kind(of: ["public.utf8-plain-text", marker]) == .ignored)
        }
    }

    @Test func filesAreIgnoredImagesBeatTextAndUnknownIsIgnored() {
        #expect(ClipboardRules.kind(of: ["public.file-url", "public.utf8-plain-text"]) == .ignored)
        #expect(ClipboardRules.kind(of: ["public.tiff", "public.utf8-plain-text"]) == .image)
        #expect(ClipboardRules.kind(of: ["public.png"]) == .image)
        #expect(ClipboardRules.kind(of: ["public.html", "public.utf8-plain-text"]) == .text)
        #expect(ClipboardRules.kind(of: ["public.url"]) == .text)
        #expect(ClipboardRules.kind(of: ["public.html"]) == .ignored)
    }

    @Test func linksAreRecognised() {
        #expect(ClipboardRules.kind(ofText: "https://github.com/Venu005/macdroid") == .link)
        #expect(ClipboardRules.kind(ofText: " http://example.com/a?b=c ") == .link)
        #expect(ClipboardRules.kind(ofText: "see https://example.com") == .text)
        #expect(ClipboardRules.kind(ofText: "ftp://example.com") == .text)
    }

    // Review Focus #3
    @Test func textThatWouldOverflowTheFrameIsRefused() {
        #expect(!ClipboardRules.fitsInAFrame(String(repeating: "\n", count: 600_000))) // escaped to 1.2 MB
        #expect(ClipboardRules.fitsInAFrame(String(repeating: "a", count: 900_000)))
        #expect(ClipboardRules.encodedSize(of: "hi") < 200)
    }
}

@Suite struct ClipboardHistoryTests {
    let date = Date(timeIntervalSince1970: 1_000_000)

    @Test func keepsCapacityNewestFirstAndPersists() throws {
        let dir = try makeTemporaryDirectory()
        var history = ClipboardHistory(directory: dir, capacity: 10)
        for i in 0..<12 { history.add(.text("item \(i)"), direction: .toPhone, id: "i\(i)", date: date) }
        #expect(history.items.count == 10)
        #expect(history.items.first?.text == "item 11")
        let reloaded = ClipboardHistory(directory: dir, capacity: 10)
        #expect(reloaded.items == history.items)
    }

    @Test func searchIsCaseInsensitiveOverText() throws {
        var history = ClipboardHistory(directory: try makeTemporaryDirectory())
        history.add(.text("Meeting moved to 4:30"), direction: .fromPhone, id: "a", date: date)
        history.add(.text("brew install xcodegen"), direction: .toPhone, id: "b", date: date)
        #expect(ClipboardPresentation.filter(history.items, query: "MEETING").map(\.id) == ["a"])
        #expect(ClipboardPresentation.filter(history.items, query: "  ").count == 2)
    }

    @Test func imagesAreStoredAsFiles() throws {
        var history = ClipboardHistory(directory: try makeTemporaryDirectory())
        let png = testBytes(500)
        let item = history.add(.image(png), direction: .fromPhone, id: "img", date: date)
        #expect(item.kind == .image)
        #expect(history.content(of: item) == .image(png))
        #expect(history.imageURL(item) != nil)
    }

    // Review Focus #5
    @Test func trimmingAndClearingDeleteImageFiles() throws {
        var history = ClipboardHistory(directory: try makeTemporaryDirectory(), capacity: 20)
        for i in 0..<20 { history.add(.image(testBytes(10, seed: UInt8(i))), direction: .toPhone, id: "p\(i)", date: date) }
        history.setCapacity(10)
        let files = try FileManager.default.contentsOfDirectory(atPath: history.imagesDirectory.path(percentEncoded: false))
        #expect(files.count == 10)
        history.clear()
        #expect(try FileManager.default.contentsOfDirectory(atPath: history.imagesDirectory.path(percentEncoded: false)).isEmpty)
        #expect(history.items.isEmpty)
    }

    @Test func unknownCapacityFallsBackToTwenty() throws {
        #expect(ClipboardHistory(directory: try makeTemporaryDirectory(), capacity: 7).capacity == 20)
    }
}

@Suite struct ClipboardSyncTests {
    actor Pasteboard {
        private(set) var applied: [ClipboardContent] = []
        private var changeCount = 100
        func apply(_ content: ClipboardContent) -> Int {
            applied.append(content)
            changeCount += 1
            return changeCount
        }
    }

    final class Harness: Sendable {
        let sync: ClipboardSync
        let sent: Collector<Message>
        let images: Collector<URL>
        let pasteboard: Pasteboard
        let events: Collector<ClipboardEvent>
        let listener: Task<Void, Never>

        init(sendToPhone: Bool = true, receiveFromPhone: Bool = true) throws {
            let sent = Collector<Message>()
            let images = Collector<URL>()
            let pasteboard = Pasteboard()
            let events = Collector<ClipboardEvent>()
            let sync = ClipboardSync(
                history: ClipboardHistory(directory: try makeTemporaryDirectory()),
                sendToPhone: sendToPhone, receiveFromPhone: receiveFromPhone,
                now: { Date(timeIntervalSince1970: 1_000_000) },
                send: { await sent.append($0) },
                sendImage: { url in await images.append(url); return true },
                apply: { await pasteboard.apply($0) }
            )
            let stream = sync.events
            self.sync = sync
            self.sent = sent
            self.images = images
            self.pasteboard = pasteboard
            self.events = events
            self.listener = Task { for await event in stream { await events.append(event) } }
        }

        func connect(features: [String] = [Feature.files, Feature.notifications, Feature.clipboard]) async {
            await sync.connectionChanged(.connected(PeerInfo(device: "Phone", app: "0.4.0", features: features)))
        }
    }

    @Test func localTextIsSentAndRecorded() async throws {
        let h = try Harness()
        await h.connect()
        await h.sync.localChange(.text("hello"), changeCount: 1)
        let sent = await h.sent.items
        guard case .clipboardSet(let body) = sent.first else { Issue.record("nothing sent"); return }
        #expect(body.text == "hello")
        #expect(await h.sync.state.items.first?.direction == .toPhone)
    }

    @Test func nothingIsSentWhenDisconnectedSwitchedOffOrThePhoneIsOld() async throws {
        let h = try Harness()
        await h.sync.localChange(.text("a"), changeCount: 1) // disconnected
        await h.connect(features: [Feature.files])
        await h.sync.localChange(.text("b"), changeCount: 2) // phone without clipboard
        await h.connect()
        await h.sync.setSendToPhone(false)
        await h.sync.localChange(.text("c"), changeCount: 3)
        #expect(await h.sent.items.isEmpty)
        #expect(await h.sync.state.items.isEmpty)
    }

    // Review Focus #2
    @Test func applyingFromThePhoneIsNotSentBack() async throws {
        let h = try Harness()
        await h.connect()
        await h.sync.handle(.clipboardSet(ClipboardSet(itemId: "x", text: "from phone")))
        #expect(await h.pasteboard.applied == [.text("from phone")])
        await h.sync.localChange(.text("from phone"), changeCount: 101) // the watcher sees our own write
        #expect(await h.sent.items.isEmpty)
        await h.sync.localChange(.text("typed later"), changeCount: 102)
        #expect(await h.sent.items.count == 1)
        try await eventually { await h.events.items.count == 1 }
    }

    // Review Focus #2
    @Test func historyCopyIsNotSent() async throws {
        let h = try Harness()
        await h.connect()
        await h.sync.localChange(.text("note"), changeCount: 1)
        let id = try #require(await h.sync.state.items.first?.id)
        await h.sync.copyToMac(id: id)
        await h.sync.localChange(.text("note"), changeCount: 101)
        #expect(await h.sent.items.count == 1)
    }

    @Test func receivingSwitchedOffIgnoresThePhone() async throws {
        let h = try Harness(receiveFromPhone: false)
        await h.sync.handle(.clipboardSet(ClipboardSet(itemId: "x", text: "hi")))
        #expect(await h.pasteboard.applied.isEmpty)
    }

    @Test func oversizedTextLeavesANote() async throws {
        let h = try Harness()
        await h.connect()
        await h.sync.localChange(.text(String(repeating: "\n", count: 600_000)), changeCount: 1)
        #expect(await h.sent.items.isEmpty)
        #expect(await h.sync.state.note == "Not sent to your phone: text over 1 MB")
    }

    @Test func localImageIsSentThroughTheTransferChannel() async throws {
        let h = try Harness()
        await h.connect()
        await h.sync.localChange(.image(testBytes(1_000)), changeCount: 1)
        #expect(await h.images.items.count == 1)
        #expect(await h.sync.state.items.first?.kind == .image)
    }

    @Test func oversizedImageLeavesANote() async throws {
        let h = try Harness()
        await h.connect()
        await h.sync.localChange(.image(Data(count: ClipboardLimits.maxImageBytes + 1)), changeCount: 1)
        #expect(await h.images.items.isEmpty)
        #expect(await h.sync.state.note == "Not sent to your phone: image over 10 MB")
    }

    @Test func receivedImageIsAppliedRecordedAndTheTransferFileRemoved() async throws {
        let h = try Harness()
        let file = try makeTemporaryDirectory().appending(path: "clipboard.png")
        let png = testBytes(700)
        try png.write(to: file)
        await h.sync.imageReceived(file)
        #expect(await h.pasteboard.applied == [.image(png)])
        #expect(await h.sync.state.items.first?.kind == .image)
        #expect(!FileManager.default.fileExists(atPath: file.path(percentEncoded: false)))
    }

    @Test func sendFromHistoryResendsText() async throws {
        let h = try Harness()
        await h.connect()
        await h.sync.handle(.clipboardSet(ClipboardSet(itemId: "x", text: "again")))
        let id = try #require(await h.sync.state.items.first?.id)
        await h.sync.sendToPhone(id: id)
        guard case .clipboardSet(let body) = await h.sent.items.first else { Issue.record("not sent"); return }
        #expect(body.text == "again")
    }
}

@Suite struct ClipboardPresentationTests {
    @Test func previewsAreOneLine() {
        let item = ClipboardItem(id: "a", kind: .text, text: "line one\nline two", direction: .toPhone, date: .now)
        #expect(ClipboardPresentation.preview(item) == "line one line two")
        let long = ClipboardItem(id: "b", kind: .text, text: String(repeating: "x", count: 300), direction: .toPhone, date: .now)
        #expect(ClipboardPresentation.preview(long).count == 120)
        #expect(ClipboardPresentation.preview(ClipboardItem(id: "c", kind: .image, text: nil, direction: .fromPhone, date: .now)) == "Image")
    }

    @Test func labelsAndNotices() {
        #expect(ClipboardPresentation.directionLabel(.toPhone) == "→ phone")
        #expect(ClipboardPresentation.directionLabel(.fromPhone) == "← from phone")
        #expect(ClipboardPresentation.pageNotice(ClipboardState(connected: true, phoneSupportsClipboard: false)) == "Update MacDroid on your phone to use this.")
        #expect(ClipboardPresentation.pageNotice(ClipboardState(connected: false)) == nil)
    }
}
